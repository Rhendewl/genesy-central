// Run with NODE_PATH pointing to a temporary installation of @electric-sql/pglite.
import { createRequire } from "node:module";
import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
const require = createRequire(import.meta.url);
const { PGlite } = require("@electric-sql/pglite");
const db = new PGlite();
const id = (n) => `00000000-0000-4000-8000-${String(n).padStart(12, "0")}`;
const [owner, other, a, b, c, shared, unused, automationTag, otherTag] = Array.from({ length: 9 }, (_, i) => id(i + 1));
await db.exec(`
CREATE SCHEMA auth; CREATE ROLE authenticated; CREATE ROLE anon; CREATE ROLE service_role;
CREATE TABLE auth.users(id uuid PRIMARY KEY);
INSERT INTO auth.users VALUES ('${owner}'),('${other}');
CREATE FUNCTION public.effective_owner_id() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT current_setting('test.owner')::uuid $$;
CREATE FUNCTION public.can_access_crm_pipeline(p uuid) RETURNS boolean LANGUAGE sql STABLE AS $$ SELECT p=current_setting('test.pipeline')::uuid $$;
CREATE TABLE crm_pipelines(id uuid PRIMARY KEY,user_id uuid NOT NULL);
GRANT SELECT ON crm_pipelines TO authenticated;
INSERT INTO crm_pipelines VALUES ('${a}','${owner}'),('${b}','${owner}'),('${c}','${other}');
CREATE TABLE tags(id uuid PRIMARY KEY,user_id uuid,name text,color text,created_at timestamptz DEFAULT now());
INSERT INTO tags(id,user_id,name,color) VALUES ('${shared}','${owner}','Interessado','#123456'),('${unused}','${owner}','Sem uso','#123456'),('${automationTag}','${owner}','Automação','#123456'),('${otherTag}','${other}','Outra empresa','#123456');
CREATE TABLE leads(id uuid PRIMARY KEY,user_id uuid,pipeline_id uuid,tags text[]);
INSERT INTO leads VALUES ('${id(20)}','${owner}','${a}',ARRAY['${shared}']),('${id(21)}','${owner}','${b}',ARRAY['${shared}']),('${id(22)}','${other}','${c}',ARRAY['${otherTag}']);
CREATE TABLE workflow_automations(pipeline_id uuid,trigger_config jsonb);
INSERT INTO workflow_automations VALUES ('${a}','{"tagId":"${automationTag}"}');
`);
await db.exec(readFileSync("supabase/migrations/20261029190000_crm_pipeline_tags.sql", "utf8"));
assert.equal((await db.query("SELECT count(*)::int AS n FROM crm_pipeline_tags")).rows[0].n, 4);
assert.equal((await db.query(`SELECT tags[1] AS tag FROM leads WHERE id='${id(20)}'`)).rows[0].tag, shared);
await db.exec(`UPDATE crm_pipeline_tags SET name='VIP' WHERE pipeline_id='${a}' AND id='${shared}';`);
assert.equal((await db.query(`SELECT name FROM crm_pipeline_tags WHERE pipeline_id='${b}' AND id='${shared}'`)).rows[0].name, "Interessado");
assert.equal((await db.query(`SELECT name FROM tags WHERE id='${shared}'`)).rows[0].name, "Interessado");
await db.exec(`INSERT INTO leads VALUES ('${id(23)}','${owner}','${b}',ARRAY['${automationTag}','${shared}']);`);
assert.deepEqual((await db.query(`SELECT tags FROM leads WHERE id='${id(23)}'`)).rows[0].tags, [shared]);
await db.exec(`SET test.owner='${owner}'; SET test.pipeline='${a}'; SET ROLE authenticated;`);
assert.equal((await db.query("SELECT count(*)::int AS n FROM crm_pipeline_tags")).rows[0].n, 2);
await assert.rejects(db.exec(`INSERT INTO crm_pipeline_tags(pipeline_id,name) VALUES ('${b}','Inválida')`), /row-level security/);
await db.exec(`RESET ROLE; SET test.owner='${other}'; SET test.pipeline='${a}'; SET ROLE authenticated;`);
assert.equal((await db.query("SELECT count(*)::int AS n FROM crm_pipeline_tags")).rows[0].n, 0);
await db.exec(`RESET ROLE; DELETE FROM crm_pipeline_tags WHERE pipeline_id='${a}' AND id='${shared}';`);
assert.equal((await db.query(`SELECT count(*)::int AS n FROM crm_pipeline_tags WHERE pipeline_id='${b}' AND id='${shared}'`)).rows[0].n, 1);
console.log("OK: legacy assignments, independent edits/deletion, workflow tags, copy isolation, pipeline and tenant RLS.");
await db.close();
